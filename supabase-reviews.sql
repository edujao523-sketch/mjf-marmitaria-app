-- MJF Marmitaria: sistema de avaliações
-- Execute este arquivo no Supabase > SQL Editor > New query.
create table if not exists public.mjf_reviews (
  id bigint generated by default as identity primary key,
  customer_name text,
  rating integer not null check (rating between 1 and 5),
  comment text,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  created_at timestamptz not null default now()
);
alter table public.mjf_reviews enable row level security;
drop policy if exists "Public can submit MJF reviews" on public.mjf_reviews;
create policy "Public can submit MJF reviews"
on public.mjf_reviews for insert to anon, authenticated
with check (status = 'pending' and rating between 1 and 5
  and (customer_name is null or char_length(customer_name) <= 50)
  and (comment is null or char_length(comment) <= 500));
drop policy if exists "Public can read approved MJF reviews" on public.mjf_reviews;
create policy "Public can read approved MJF reviews"
on public.mjf_reviews for select to anon, authenticated
using (status = 'approved');
grant usage on schema public to anon, authenticated;
grant insert (customer_name, rating, comment) on public.mjf_reviews to anon, authenticated;
grant select (id, customer_name, rating, comment, created_at) on public.mjf_reviews to anon, authenticated;
